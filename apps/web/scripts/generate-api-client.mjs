#!/usr/bin/env node
/**
 * Regenerates lib/api/generated/client.ts from apps/api/openapi.json.
 *
 * Phase 0 non-negotiable rule (docs/plans, packages/shared/src/index.ts):
 * frontend validation must be generated from the backend's OpenAPI spec, not
 * hand-written, so the two cannot drift. This script is the one place that
 * rule is actually enforced mechanically -- see also
 * scripts/check-api-client-fresh.mjs, which fails CI if someone changes
 * apps/api/openapi.json (or the generator's flags) without re-running this
 * and committing the result.
 *
 * Run after any change to apps/api's route/Pydantic schema definitions:
 *   cd apps/api && .venv/Scripts/python.exe scripts/export_openapi.py
 *   cd apps/web && npm run generate:api-client
 */
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(here, "..");
const openapiPath = path.resolve(webRoot, "../api/openapi.json");
const outPath = path.resolve(webRoot, "lib/api/generated/client.ts");

const BANNER = `/**
 * AUTO-GENERATED by \`npm run generate:api-client\` (openapi-zod-client) from
 * apps/api/openapi.json. DO NOT EDIT BY HAND -- your changes will be
 * overwritten the next time this is regenerated, and a hand-edited copy
 * defeats the whole point of generating it (see packages/shared/src/index.ts
 * and docs/DECISIONS.md's "OpenAPI-generated client" entry).
 *
 * Regenerate with:
 *   cd apps/api && .venv/Scripts/python.exe scripts/export_openapi.py
 *   cd apps/web && npm run generate:api-client
 *
 * scripts/check-api-client-fresh.mjs fails CI if this file is stale
 * relative to apps/api/openapi.json.
 */
`;

export function generate(destPath = outPath) {
  const cmd = `npx --no-install openapi-zod-client "${openapiPath}" -o "${destPath}" --export-schemas`;
  execSync(cmd, { cwd: webRoot, stdio: "inherit" });
  const generated = readFileSync(destPath, "utf8");
  writeFileSync(destPath, BANNER + generated);
}

generate();
